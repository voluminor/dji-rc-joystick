package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// // // // // // // // // //

const (
	validEnglish = `{
		"language.name": "English",
		"home.title": "Home"
	}`
	validRussian = `{
		"language.name": "Русский",
		"home.title": "Главная"
	}`
)

// //

func writeTestFile(t *testing.T, directory string, name string, content string) {
	t.Helper()

	if err := os.WriteFile(filepath.Join(directory, name), []byte(content), 0644); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}
}

func prepareValidSource(t *testing.T) string {
	t.Helper()

	directory := t.TempDir()
	writeTestFile(t, directory, "en.json", validEnglish)
	writeTestFile(t, directory, "ru-RU.json", validRussian)
	return directory
}

func requireGenerationError(t *testing.T, files map[string]string, expected string) {
	t.Helper()

	directory := t.TempDir()
	for name, content := range files {
		writeTestFile(t, directory, name, content)
	}

	err := generate(directory, filepath.Join(t.TempDir(), "languages_gen.go"), "language")
	if err == nil {
		t.Fatal("generate() accepted invalid input")
	}
	if !strings.Contains(err.Error(), expected) {
		t.Fatalf("generate() error = %q, want substring %q", err, expected)
	}
}

// //

func TestGenerate(t *testing.T) {
	sourceDir := prepareValidSource(t)
	outputPath := filepath.Join(t.TempDir(), "languages_gen.go")

	if err := generate(sourceDir, outputPath, "language"); err != nil {
		t.Fatalf("generate() error = %v", err)
	}

	data, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}
	content := string(data)
	for _, expected := range []string{
		"// Code generated by go generate; DO NOT EDIT.",
		"package language",
		`"en":    "English"`,
		`"ru-RU": "Русский"`,
		`"Главная"`,
		"func Keys() []string",
		"func Supports(key string) bool",
		"func Get(languageKey string, translationKey string) (string, bool)",
	} {
		if !strings.Contains(content, expected) {
			t.Errorf("generated file does not contain %q", expected)
		}
	}
}

func TestGenerateRequiresEnglish(t *testing.T) {
	requireGenerationError(t, map[string]string{
		"ru-RU.json": validRussian,
	}, "en.json is required")
}

func TestGenerateRejectsMalformedJSON(t *testing.T) {
	requireGenerationError(t, map[string]string{
		"en.json": `{"language.name":`,
	}, "decode value")
}

func TestGenerateRejectsDuplicateKeys(t *testing.T) {
	requireGenerationError(t, map[string]string{
		"en.json": `{"language.name":"English","language.name":"Other"}`,
	}, `duplicate key "language.name"`)
}

func TestGenerateRejectsNonStringValues(t *testing.T) {
	requireGenerationError(t, map[string]string{
		"en.json": `{"language.name":"English","home.title":1}`,
	}, `key "home.title"`)
}

func TestGenerateRejectsEmptyKeysAndValues(t *testing.T) {
	tests := map[string]struct {
		content  string
		expected string
	}{
		"empty key": {
			content:  `{"language.name":"English","":"value"}`,
			expected: "empty key",
		},
		"empty value": {
			content:  `{"language.name":"English","home.title":""}`,
			expected: `empty value for key "home.title"`,
		},
	}

	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			requireGenerationError(t, map[string]string{
				"en.json": test.content,
			}, test.expected)
		})
	}
}

func TestGenerateRequiresLanguageName(t *testing.T) {
	tests := map[string]struct {
		content  string
		expected string
	}{
		"missing": {
			content:  `{"home.title":"Home"}`,
			expected: `missing required key "language.name"`,
		},
		"blank": {
			content:  `{"language.name":" "}`,
			expected: `empty value for key "language.name"`,
		},
	}

	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			requireGenerationError(t, map[string]string{
				"en.json": test.content,
			}, test.expected)
		})
	}
}

func TestGenerateRejectsKeyMismatch(t *testing.T) {
	requireGenerationError(t, map[string]string{
		"en.json": validEnglish,
		"de.json": `{
			"language.name": "Deutsch",
			"additional": "Zusätzlich"
		}`,
		"ru-RU.json": `{
			"language.name": "Русский"
		}`,
	}, "additional keys: additional")

	directory := t.TempDir()
	writeTestFile(t, directory, "en.json", validEnglish)
	writeTestFile(t, directory, "de.json", `{"language.name":"Deutsch","additional":"Zusätzlich"}`)
	writeTestFile(t, directory, "ru-RU.json", `{"language.name":"Русский"}`)

	err := generate(directory, filepath.Join(t.TempDir(), "languages_gen.go"), "language")
	if err == nil {
		t.Fatal("generate() accepted mismatched keys")
	}
	if !strings.Contains(err.Error(), "de.json") || !strings.Contains(err.Error(), "ru-RU.json") {
		t.Fatalf("generate() error does not list every mismatched file: %v", err)
	}
	if !strings.Contains(err.Error(), "missing keys: home.title") {
		t.Fatalf("generate() error does not list missing key: %v", err)
	}
}

func TestGenerateAcceptsMatchingFormatDirectives(t *testing.T) {
	directory := t.TempDir()
	writeTestFile(t, directory, "en.json", `{
		"language.name":"English",
		"home.connect.message":"Connecting to %s:%d. Progress: 100%%."
	}`)
	writeTestFile(t, directory, "de.json", `{
		"language.name":"Deutsch",
		"home.connect.message":"Verbindung mit %s:%d wird hergestellt. Fortschritt: 100%%."
	}`)

	if err := generate(directory, filepath.Join(t.TempDir(), "languages_gen.go"), "language"); err != nil {
		t.Fatalf("generate() error = %v", err)
	}
}

func TestGenerateRejectsFormatDirectiveMismatch(t *testing.T) {
	tests := map[string]string{
		"missing":   "Verbindung mit %s wird hergestellt.",
		"added":     "Verbindung mit %s:%d wird hergestellt: %d.",
		"reordered": "Verbindung mit %d:%s wird hergestellt.",
		"changed":   "Verbindung mit %s:%s wird hergestellt.",
	}

	for name, translation := range tests {
		t.Run(name, func(t *testing.T) {
			requireGenerationError(t, map[string]string{
				"en.json": `{
					"language.name":"English",
					"home.connect.message":"Connecting to %s:%d."
				}`,
				"de.json": `{
					"language.name":"Deutsch",
					"home.connect.message":` + fmt.Sprintf("%q", translation) + `
				}`,
			}, `de.json has formatting directive mismatch: key "home.connect.message"`)
		})
	}
}

func TestGenerateRejectsInvalidLanguageFilename(t *testing.T) {
	requireGenerationError(t, map[string]string{
		"en.json":       validEnglish,
		"invalid_.json": validRussian,
	}, `invalid language filename "invalid_.json"`)
}

func TestGenerateIsDeterministic(t *testing.T) {
	sourceDir := prepareValidSource(t)
	outputPath := filepath.Join(t.TempDir(), "languages_gen.go")

	if err := generate(sourceDir, outputPath, "language"); err != nil {
		t.Fatalf("first generate() error = %v", err)
	}
	first, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatalf("read first output: %v", err)
	}

	if err = generate(sourceDir, outputPath, "language"); err != nil {
		t.Fatalf("second generate() error = %v", err)
	}
	second, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatalf("read second output: %v", err)
	}
	if string(first) != string(second) {
		t.Fatal("generate() produced different output for unchanged input")
	}
}

func TestGeneratePreservesOutputAfterFailure(t *testing.T) {
	sourceDir := prepareValidSource(t)
	outputPath := filepath.Join(t.TempDir(), "languages_gen.go")

	if err := generate(sourceDir, outputPath, "language"); err != nil {
		t.Fatalf("valid generate() error = %v", err)
	}
	before, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatalf("read valid output: %v", err)
	}

	writeTestFile(t, sourceDir, "ru-RU.json", `{"language.name":"Русский"}`)
	if err = generate(sourceDir, outputPath, "language"); err == nil {
		t.Fatal("generate() accepted invalid replacement input")
	}

	after, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatalf("read preserved output: %v", err)
	}
	if string(before) != string(after) {
		t.Fatal("failed generation changed the existing output")
	}
}
